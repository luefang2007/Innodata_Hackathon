"""Local validation gates, run before a package is emitted (no Docker, seconds per task).

Gates (all must pass):
  hygiene      spec has no authoring/AI tells and does not mention tests or the reference solution
  grounding    the gold edits existing click modules (not an orphan file)
  gold_tests   every new test passes with the gold applied
  feature_absent  the new tests fail on the untouched base (>= MIN_F2P_TESTS of them, and few pass at base)
  regression   coverage-selected existing tests pass at base AND with the gold
  mutation     corrupting the gold's added lines makes the feature tests fail
  fairness     every word of an asserted message is in the spec, the test's own inputs or click's source
  novelty      the feature tests do not pass on live upstream main
"""
from __future__ import annotations

import ast
import hashlib
import random
import re
from dataclasses import dataclass, field
from pathlib import Path

from . import config, covmap, repo
from .runner import run_pytest, tail

TELL_RE = re.compile(r"\b(as an ai|language model|chatgpt|openai|i apologize|i cannot assist|"
                     r"generated by (an )?ai)\b", re.I)
SPEC_LEAK_RE = re.compile(r"(fail_to_pass|pass_to_pass|test_patch|reference (implementation|solution)|"
                          r"gold (patch|solution)|hidden tests?|the grader|tests/test_)", re.I)
# words of 3+ letters; an apostrophe counts only inside a word ("isn't"), never a closing quote ("'old'")
WORD_RE = re.compile(r"[A-Za-z]{3,}(?:'[A-Za-z]+)*")


@dataclass
class Candidate:
    spec: str
    gold_patch: str
    test_patch: str
    test_path: str
    test_content: str
    extra_test_paths: list = field(default_factory=list)   # composite tasks carry several test files
    p2p_limit: int = config.MAX_P2P_TESTS

    @property
    def paths(self) -> list[str]:
        return [self.test_path, *self.extra_test_paths]


@dataclass
class Report:
    gates: dict = field(default_factory=dict)
    f2p: list = field(default_factory=list)
    p2p: list = field(default_factory=list)
    mutation: dict = field(default_factory=dict)
    warnings: list = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return bool(self.gates) and all(g["ok"] for g in self.gates.values())

    def gate(self, name: str, ok: bool, detail: str = "") -> bool:
        self.gates[name] = {"ok": bool(ok), "detail": detail}
        return ok

    def failures_text(self) -> str:
        out = []
        for name, g in self.gates.items():
            if not g["ok"]:
                out.append(f"[{name}] FAILED\n{g['detail']}")
        return "\n\n".join(out) or "(no failures)"

    def summary(self) -> dict:
        return {"ok": self.ok, "gates": {k: v["ok"] for k, v in self.gates.items()},
                "n_f2p": len(self.f2p), "n_p2p": len(self.p2p), "mutation": self.mutation,
                "warnings": self.warnings}


# ------------------------------------------------------------------------------------------------
# building a candidate from model output
# ------------------------------------------------------------------------------------------------

def apply_edits(wc: Path, edits: list[dict]) -> tuple[list[str], list[str]]:
    """Apply search/replace edits under src/click/ in a work copy. Returns (touched paths, errors)."""
    errors: list[str] = []
    touched: list[str] = []
    for i, ed in enumerate(edits):
        path = ed["path"].strip().lstrip("./").replace("\\", "/")
        if not path.startswith("src/click/") or not path.endswith(".py"):
            errors.append(f"edit {i}: path {path!r} is outside src/click/*.py")
            continue
        fpath = wc / path
        search = ed["search"].replace("\r\n", "\n")
        replace = ed["replace"].replace("\r\n", "\n")
        if not fpath.exists():
            if search.strip():
                errors.append(f"edit {i}: {path} does not exist (use an empty search to create a new module)")
                continue
            repo.write_text(fpath, replace)
        else:
            text = repo.read_text(fpath)
            n = text.count(search) if search else 0
            if n != 1:
                errors.append(f"edit {i}: search block matches {n} times in {path} (must match exactly once):\n"
                              f"{search[:400]}")
                continue
            repo.write_text(fpath, text.replace(search, replace, 1))
        if path not in touched:
            touched.append(path)
    for path in touched:
        try:
            compile(repo.read_text(wc / path), path, "exec")
        except SyntaxError as exc:
            errors.append(f"{path}: SyntaxError after edits: {exc}")
    return touched, errors


def build_candidate(edits: list[dict], test_content: str, test_path: str, spec: str,
                    pre_patch: str = "") -> tuple[Candidate | None, str]:
    """Turn a model answer into a candidate: the gold as one diff against the base, plus the test file.

    `pre_patch` is a gold diff that is applied to the base first; the edits are then a delta on top of
    it, and the resulting gold is again one diff against the base."""
    with repo.workcopy(config.BASE_SNAPSHOT) as wc:
        before: list[str] = []
        if pre_patch.strip():
            ok, err = repo.apply_patch(wc, pre_patch)
            if not ok:
                return None, f"the current gold does not apply to the base source: {err[:500]}"
            before = re.findall(r"^\+\+\+ b/(\S+)", pre_patch, re.M)
        touched, errors = apply_edits(wc, edits)
        if errors:
            return None, "\n".join(errors)
        gold = repo.diff_against_head(wc, list(dict.fromkeys([*before, *touched])))
    if not gold.strip():
        return None, "the edits produce an empty gold patch"
    with repo.workcopy(config.BASE_SNAPSHOT) as wc:
        if (wc / test_path).exists():
            return None, f"{test_path} already exists in click; the test file must be new"
        repo.write_text(wc / test_path, test_content)
        try:
            compile(test_content, test_path, "exec")
        except SyntaxError as exc:
            return None, f"{test_path}: SyntaxError: {exc}"
        test_patch = repo.diff_against_head(wc, [test_path])
    return Candidate(spec=spec, gold_patch=gold, test_patch=test_patch, test_path=test_path,
                     test_content=test_content), ""


def _text_edit(text: str, ed: dict, i: int, label: str) -> tuple[str, str]:
    """One search/replace edit on a text (the test file or instruction.md). An empty search appends."""
    search = ed["search"].replace("\r\n", "\n")
    replace = ed["replace"].replace("\r\n", "\n")
    if not search.strip():
        return text.rstrip("\n") + "\n\n\n" + replace.strip("\n") + "\n", ""
    n = text.count(search)
    if n != 1:
        return text, (f"edit {i}: search block matches {n} times in {label} (must match exactly once):\n"
                      f"{search[:400]}")
    return text.replace(search, replace, 1), ""


def build_delta_candidate(prev: Candidate, edits: list[dict], test_path: str) -> tuple[Candidate | None, str]:
    """Rebuild a candidate from a delta: search/replace edits against the CURRENT task.

    `path` selects what an edit changes: a file under src/click/ (as it is with the current gold applied),
    the test file, or instruction.md. `prev` is not modified; the new gold is one diff against the base."""
    spec, tests, src, errors = prev.spec, prev.test_content, [], []
    for i, ed in enumerate(edits):
        path = ed["path"].strip().lstrip("./").replace("\\", "/")
        err = ""
        if path == test_path:
            tests, err = _text_edit(tests, ed, i, path)
        elif path.lower() == "instruction.md":
            spec, err = _text_edit(spec, ed, i, "instruction.md")
        else:
            src.append(ed)
        if err:
            errors.append(err)
    if errors:
        return None, "\n".join(errors)
    if not src and spec == prev.spec and tests == prev.test_content:
        return None, "the answer contains no edit: nothing would change"
    return build_candidate(src, tests, test_path, spec, pre_patch=prev.gold_patch)


# ------------------------------------------------------------------------------------------------
# the gates
# ------------------------------------------------------------------------------------------------

def run_gates(c: Candidate) -> Report:
    r = Report()
    leak = TELL_RE.search(c.spec) or SPEC_LEAK_RE.search(c.spec)
    r.gate("hygiene", not leak, f"instruction.md contains {leak.group(0)!r}" if leak else "")
    existing = re.findall(r"^--- a/(src/click/\S+)", c.gold_patch, re.M)
    r.gate("grounding", bool(existing), "" if existing else "the gold only adds new files; it must extend "
                                                          "existing click modules")

    p2p_candidates = covmap.select_p2p(c.gold_patch, config.BASE_SNAPSHOT, limit=c.p2p_limit)

    # --- base (feature absent) ---------------------------------------------------------------
    with repo.workcopy(config.BASE_SNAPSHOT) as wc:
        ok, err = repo.apply_patch(wc, c.test_patch)
        if not ok:
            r.gate("feature_absent", False, f"test patch does not apply: {err}")
            return r
        st_base, _ = run_pytest(wc, [*c.paths, *p2p_candidates])

    # --- gold applied --------------------------------------------------------------------------
    with repo.workcopy(config.BASE_SNAPSHOT) as wc:
        ok, err = repo.apply_patch(wc, c.gold_patch)
        if not ok:
            r.gate("gold_tests", False, f"gold patch does not apply: {err}")
            return r
        repo.apply_patch(wc, c.test_patch)
        st_gold, log_gold = run_pytest(wc, [*c.paths, *p2p_candidates])
        new_tests = sorted(t for t in st_gold if any(t.startswith(p) for p in c.paths))
        bad = [t for t in new_tests if st_gold[t] != "PASSED"]
        if not new_tests:
            r.gate("gold_tests", False, "no tests were collected from the new test file:\n" + tail(log_gold, 40))
            return r
        r.gate("gold_tests", not bad, ("tests failing with the gold applied:\n" + "\n".join(bad) +
                                       "\n\npytest output (tail):\n" + tail(log_gold, 80)) if bad else
               f"{len(new_tests)} new tests pass")

        f2p = [t for t in new_tests if st_gold[t] == "PASSED" and st_base.get(t) != "PASSED"]
        passing_at_base = [t for t in new_tests if st_base.get(t) == "PASSED"]
        r.f2p = f2p
        weak = len(passing_at_base) > max(1, len(new_tests) // 5)
        r.gate("feature_absent", len(f2p) >= config.MIN_F2P_TESTS and not weak,
               f"{len(f2p)} feature tests fail at base (need >= {config.MIN_F2P_TESTS}); "
               f"{len(passing_at_base)} new tests already pass without the feature"
               + (": " + ", ".join(passing_at_base) if passing_at_base else ""))
        if passing_at_base:
            r.warnings.append(f"{len(passing_at_base)} new tests pass at base and are not graded")

        p2p = [t for t in p2p_candidates if st_base.get(t) == "PASSED"]
        broken = [t for t in p2p if st_gold.get(t) != "PASSED"]
        r.p2p = [t for t in p2p if t not in broken]
        r.gate("regression", not broken and len(r.p2p) >= config.MIN_P2P_TESTS,
               ("existing tests broken by the gold:\n" + "\n".join(broken[:20])) if broken else
               f"{len(r.p2p)} curated existing tests stay green (need >= {config.MIN_P2P_TESTS})")

        if r.gates["gold_tests"]["ok"] and f2p:
            r.mutation = mutation_check(wc, c, f2p)
            m = r.mutation
            r.gate("mutation", m["n"] > 0 and m["kill_rate"] >= config.MIN_MUTATION_KILL,
                   f"{m['killed']}/{m['n']} mutants of the gold caught by the feature tests "
                   f"(need >= {config.MIN_MUTATION_KILL:.0%}). Surviving mutants (the tests did not notice):\n"
                   + "\n".join(m["survivors"][:8]))

    r.gate("fairness", *fairness_check(c))

    # --- novelty against live upstream main ----------------------------------------------------
    if config.MAIN_SNAPSHOT.exists() and f2p:
        with repo.workcopy(config.MAIN_SNAPSHOT) as wc:
            ok, err = repo.apply_patch(wc, c.test_patch)
            st_main, _ = run_pytest(wc, c.paths) if ok else ({}, err)
        on_main = [t for t in f2p if st_main.get(t) == "PASSED"]
        r.gate("novelty", len(on_main) < len(f2p),
               f"{len(on_main)}/{len(f2p)} feature tests already pass on upstream main")
    return r


# ------------------------------------------------------------------------------------------------
# mutation testing of the gold
# ------------------------------------------------------------------------------------------------

_OPS = [
    (re.compile(r" == "), " != "), (re.compile(r" != "), " == "),
    (re.compile(r" <= "), " < "), (re.compile(r" >= "), " > "),
    (re.compile(r" < "), " <= "), (re.compile(r" > "), " >= "),
    (re.compile(r" and "), " or "), (re.compile(r" or "), " and "),
    (re.compile(r"\bTrue\b"), "False"), (re.compile(r"\bFalse\b"), "True"),
    (re.compile(r"\bnot "), ""),
    (re.compile(r"(?<![\w.])(\d+)(?![\w.])"), lambda m: str(int(m.group(1)) + 1)),
    (re.compile(r"(\"|')([^\"'\\]{2,})\1"), lambda m: f"{m.group(1)}X{m.group(2)}{m.group(1)}"),
    (re.compile(r"\breturn (?!None\b)\S.*$"), "return None"),
]


def _added_lines(patch: str) -> list[tuple[str, int, str]]:
    out, cur, new_ln = [], None, 0
    for line in patch.splitlines():
        if line.startswith("+++ b/"):
            cur = line[6:].strip()
        elif line.startswith("@@"):
            m = re.match(r"@@ -\d+(?:,\d+)? \+(\d+)", line)
            new_ln = int(m.group(1)) if m else 0
        elif cur and line.startswith("+") and not line.startswith("+++"):
            out.append((cur, new_ln, line[1:]))
            new_ln += 1
        elif cur and not line.startswith("-"):
            new_ln += 1
    return out


def _is_code(text: str) -> bool:
    s = text.strip()
    return bool(s) and not s.startswith(("#", '"""', "'''", "@")) and not re.fullmatch(r"[rbfu]?[\"'].*[\"'],?", s)


def _string_lines(text: str) -> set[int]:
    """Lines that sit inside docstrings / multi-line string literals (mutating them is a no-op)."""
    lines: set[int] = set()
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return lines
    for node in ast.walk(tree):
        if isinstance(node, ast.Expr) and isinstance(getattr(node, "value", None), ast.Constant) \
                and isinstance(node.value.value, str):
            lines |= set(range(node.lineno, (node.end_lineno or node.lineno) + 1))
        elif isinstance(node, ast.Constant) and isinstance(node.value, str) and node.end_lineno \
                and node.end_lineno > node.lineno:
            lines |= set(range(node.lineno, node.end_lineno + 1))
    return lines


def mutation_check(wc: Path, c: Candidate, f2p: list[str]) -> dict:
    mutants = []
    doc_lines: dict[str, set[int]] = {}
    for path, ln, text in _added_lines(c.gold_patch):
        if path not in doc_lines:
            doc_lines[path] = _string_lines(repo.read_text(wc / path)) if (wc / path).exists() else set()
        if not _is_code(text) or ln in doc_lines[path]:
            continue
        for pat, rep in _OPS:
            if pat.search(text):
                mutants.append((path, ln, text, pat.sub(rep, text, count=1)))
        s = text.strip()
        if not s.endswith(":") and not s.startswith(("def ", "class ", "return", "elif", "else", "try",
                                                      "except", "finally", ")", "]", "}")):
            indent = text[: len(text) - len(text.lstrip())]
            mutants.append((path, ln, text, indent + "pass"))
    seed = int(hashlib.sha256(c.gold_patch.encode()).hexdigest()[:8], 16)
    rng = random.Random(seed)
    rng.shuffle(mutants)
    killed, tried, survivors = 0, 0, []
    for path, ln, orig, mutated in mutants:
        if tried >= config.MUTANTS_PER_TASK:
            break
        if mutated == orig:
            continue
        fpath = wc / path
        original_text = repo.read_text(fpath)
        lines = original_text.split("\n")
        if ln - 1 >= len(lines) or lines[ln - 1] != orig:
            continue
        lines[ln - 1] = mutated
        new_text = "\n".join(lines)
        try:
            compile(new_text, path, "exec")
        except SyntaxError:
            continue
        repo.write_text(fpath, new_text)
        try:
            st, _ = run_pytest(wc, c.paths, extra=["-x", "-q"], timeout=300)
        finally:
            repo.write_text(fpath, original_text)
        tried += 1
        if any(st.get(t) != "PASSED" for t in f2p):
            killed += 1
        else:
            survivors.append(f"{path}:{ln}: `{orig.strip()}` -> `{mutated.strip()}`")
    return {"n": tried, "killed": killed, "kill_rate": round(killed / tried, 3) if tried else 0.0,
            "survivors": survivors}


# ------------------------------------------------------------------------------------------------
# fairness: asserted wording must come from the spec
# ------------------------------------------------------------------------------------------------

_vocab_cache: set[str] | None = None


def _click_vocab() -> set[str]:
    global _vocab_cache
    if _vocab_cache is None:
        words = set()
        for p in (config.BASE_SNAPSHOT / "src" / "click").glob("*.py"):
            words |= {w.lower() for w in WORD_RE.findall(repo.read_text(p))}
        _vocab_cache = words
    return _vocab_cache


def fairness_check(c: Candidate) -> tuple[bool, str]:
    try:
        tree = ast.parse(c.test_content)
    except SyntaxError as exc:
        return False, f"test file does not parse: {exc}"
    asserted: list[str] = []
    in_assert: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Assert):
            for sub in ast.walk(node):
                in_assert.add(id(sub))
                if isinstance(sub, ast.Constant) and isinstance(sub.value, str):
                    asserted.append(sub.value)
        elif isinstance(node, ast.Call) and getattr(node.func, "attr", "") == "raises":
            for kw in node.keywords:
                if kw.arg == "match" and isinstance(kw.value, ast.Constant) and isinstance(kw.value.value, str):
                    asserted.append(kw.value.value)
                    in_assert.add(id(kw.value))
    inputs = " ".join(n.value for n in ast.walk(tree)
                      if isinstance(n, ast.Constant) and isinstance(n.value, str) and id(n) not in in_assert)
    known = ({w.lower() for w in WORD_RE.findall(c.spec)} | {w.lower() for w in WORD_RE.findall(inputs)}
             | _click_vocab())
    problems = []
    for s in asserted:
        words = WORD_RE.findall(s)
        if len(words) < 2:
            continue
        missing = sorted({w for w in words if w.lower() not in known})
        if missing:
            problems.append(f"asserted text {s[:120]!r} uses words not found in instruction.md: {missing}")
    return (not problems), ("\n".join(problems[:15]) if problems else
                            f"{len(asserted)} asserted strings checked against the spec")
